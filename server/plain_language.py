def translate(text: str) -> str:
    """将专业术语替换为大白话。按词组长度降序替换，避免短词误替换长词。"""
    if not text:
        return text
    for term in sorted(TERM_MAP, key=len, reverse=True):
        if term in text:
            text = text.replace(term, TERM_MAP[term])
    return text


# ---------------- "所以呢？"过滤器 ----------------

_ACTION_HINTS = (
    "建议", "要不要", "试试", "记得", "先", "别忘", "赶紧", "明天",
    "打个电话", "催", "补", "查", "核对", "问", "找", "换", "砍",
    "打个电话", "补录", "登记", "记录", "记一笔", "建",
)


def has_action(text: str) -> bool:
    """检查输出是否包含可执行的行动建议。"""
    if not text:
        return False
    return any(hint in text for hint in _ACTION_HINTS)


def so_what_check(text: str, fallback_hint: str = "你要不要先看看这笔账？") -> str:
    """确保输出通过"所以呢？"测试：用户看完知道该做什么。

    如果没有行动建议，自动在末尾补一句。
    """
    if not text:
        return text
    if has_action(text):
        return text
    # 找最后一个句号/感叹号/问号，在其后追加
    for punct in ("。", "！", "？", "\n"):
        idx = text.rfind(punct)
        if idx > 0 and idx < len(text) - 1:
            return text[:idx + 1] + fallback_hint + text[idx + 1:]
    return text + fallback_hint


def polish(text: str) -> str:
    """一站式处理：术语翻译 + "所以呢"检查。所有 AI 输出统一走这里。"""
    if not text:
        return text
    return so_what_check(translate(text))